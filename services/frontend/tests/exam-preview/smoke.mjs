async function call(path, method = 'GET', body, auth = true) {
    const response = await fetch(origin + path, { method, headers: { 'Content-Type': 'application/json', ...(auth && access ? { Authorization: `Bearer ${access}` } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    return { status: response.status, data: await response.json() };
}
